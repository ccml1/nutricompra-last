import { mapTpcaRow, TpcaCsvRow } from './tpca-csv';

// Row copied verbatim from data/nutricompra-foods-v1.csv (id 2).
const arrozBlanco: TpcaCsvRow = {
  id: '2',
  name: 'Arroz blanco',
  category: 'Cereales',
  type: 'basic',
  reference_amount: '100',
  reference_unit: 'g',
  energy_kcal: '358',
  protein_g: '7.8',
  carbohydrate_g: '77.6',
  fat_g: '0.7',
  fiber_g: '',
  sodium_mg: '19',
  calcium_mg: '6',
  iron_mg: '1.04',
  source: 'TPCA',
  source_version: '2023',
  source_code: 'A3',
  source_name: 'Arroz blanco corriente',
};

// Row copied verbatim from data/nutricompra-foods-v1.csv (id 71).
const zapallo: TpcaCsvRow = {
  id: '71',
  name: 'Zapallo',
  category: 'Verduras',
  type: 'basic',
  reference_amount: '100',
  reference_unit: 'g',
  energy_kcal: '47',
  protein_g: '2.2',
  carbohydrate_g: '12.7',
  fat_g: '0.1',
  fiber_g: '1.3',
  sodium_mg: '0',
  calcium_mg: '26',
  iron_mg: '0.32',
  source: 'TPCA',
  source_version: '2023',
  source_code: 'B89',
  source_name: 'Zapallo macre',
};

describe('mapTpcaRow', () => {
  it('convierte la fila de "Arroz blanco" en alimento, perfil nutricional (por 100 g) y fuente TPCA 2023 · A3 · "Arroz blanco corriente"', () => {
    const record = mapTpcaRow(arrozBlanco);

    expect(record.food).toEqual({
      name: 'Arroz blanco',
      category: 'Cereales',
      type: 'basic',
    });
    expect(record.profile).toMatchObject({
      referenceAmount: 100,
      referenceUnit: 'g',
      energyKcal: 358,
      proteinG: 7.8,
      carbohydrateG: 77.6,
      fatG: 0.7,
      sodiumMg: 19,
      calciumMg: 6,
      ironMg: 1.04,
    });
    expect(record.source).toEqual({
      name: 'TPCA',
      version: '2023',
      sourceCode: 'A3',
      sourceName: 'Arroz blanco corriente',
    });
  });

  it('guarda como null un nutriente vacío (fibra del arroz blanco)', () => {
    const record = mapTpcaRow(arrozBlanco);

    expect(record.profile.fiberG).toBeNull();
  });

  it('conserva como 0 un valor medido en cero (sodio del zapallo)', () => {
    const record = mapTpcaRow(zapallo);

    expect(record.profile.sodiumMg).toBe(0);
  });

  it('no usa la columna id del CSV como id del alimento', () => {
    const record = mapTpcaRow(arrozBlanco);

    // Ids are UUIDs generated by the database, never the CSV's 1–78.
    expect(record.food).not.toHaveProperty('id');
    expect(record.profile).not.toHaveProperty('id');
    expect(record.source).not.toHaveProperty('id');
  });
});
